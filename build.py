TOC_SLOTS = 3


def _cover(doc):
    c = doc.c
    d_cover(c, W_, H_)
    c.bookmarkPage('p1')
    c.addOutlineEntry('Обложка', 'p1', 0, 0)
    c.showPage()
    doc.n = 1
    doc.registry.append({'n': 1, 'tag': 'ОБЛОЖКА', 'title': 'Обложка', 'dest': 'p1', 'level': 0})


def _toc_pages(doc, toc_from):
    if toc_from is None:
        for i in range(TOC_SLOTS):
            title = 'Содержание' if i == 0 else 'Содержание (продолжение)'
            doc.page('teal', 'СОДЕРЖАНИЕ', title, [
                P('Сейчас собирается оглавление… При повторной сборке здесь появятся ссылки на все страницы.'),
            ])
        return
    usable = [e for e in toc_from if e['tag'] not in ('ОБЛОЖКА', 'СОДЕРЖАНИЕ')]
    n = len(usable)
    size = max(1, (n + TOC_SLOTS - 1) // TOC_SLOTS)
    for i in range(TOC_SLOTS):
        title = 'Содержание' if i == 0 else 'Содержание (продолжение)'
        chunk = usable[i * size:(i + 1) * size]
        if chunk:
            story = doc.toc_story(chunk)
        else:
            story = [P('Все разделы перечислены на предыдущих страницах.')]
        doc.page('teal', 'СОДЕРЖАНИЕ', title, story)



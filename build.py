def build_book(path, toc_from=None):
    global doc, c, L1
    doc = Doc(path, BOOK_TITLE)
    c = doc.c
    L1 = 'blue'
    _cover(doc)
    _toc_pages(doc, toc_from)
    _body()
    doc.save()
    return doc


